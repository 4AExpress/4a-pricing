-- Ο κωδικός συνεργασίας γίνεται ΥΠΟΧΡΕΩΤΙΚΟΣ για την ολοκλήρωση.
--
-- ΑΝΤΙΣΤΡΟΦΗ ΠΡΟΗΓΟΥΜΕΝΗΣ ΑΠΟΦΑΣΗΣ, ρητά (25/09, απόγευμα).
-- Το πρωί γράφτηκε «καθοδηγούμε, δεν εμποδίζουμε»: ξεθωριασμένο κουμπί
-- και επιβεβαίωση, ποτέ φραγή, με το επιχείρημα ότι μια φραγή παράγει
-- ψεύτικα «ολοκληρώθηκε». Το ίδιο απόγευμα δύο εργασίες open_code
-- έκλεισαν με κενό κωδικό (#34, #39) — η μία από άνθρωπο που ΔΕΝ είχε
-- δει καν την προειδοποίηση, γιατί το frontend δεν είχε ανέβει.
--
-- Το επιχείρημα δεν καταρρίπτεται, ΠΑΡΑΚΑΜΠΤΕΤΑΙ: το «Δεν εφαρμόζεται»
-- μένει πάντα ανοιχτό, με υποχρεωτικό λόγο. Όποιος πραγματικά δεν
-- μπορεί να καταχωρήσει κωδικό έχει έξοδο που ΛΕΕΙ ΤΗΝ ΑΛΗΘΕΙΑ, αντί να
-- γράψει «ολοκληρώθηκε» σε κάτι που δεν έγινε. Χωρίς αυτή τη βαλβίδα, η
-- φραγή θα ήταν λάθος.
--
-- ΚΑΝΟΝΑΣ SERVER: MySQL 8.4.6 — ΟΧΙ `ADD COLUMN IF NOT EXISTS`.

-- ── 1. Η στήλη ────────────────────────────────────────────────────────
-- DEFAULT 0: κάθε υπάρχων και κάθε μελλοντικός τύπος εργασίας παραμένει
-- υπόδειξη. Η φραγή είναι ρητή επιλογή ανά τύπο, ποτέ προεπιλογή.
SET @sql = (
  SELECT IF(
    COUNT(*) = 0,
    'ALTER TABLE `4a_task_types`
       ADD COLUMN `ready_enforced` TINYINT(1) NOT NULL DEFAULT 0
       COMMENT ''1 = το ready_check ειναι ΦΡΑΓΜΑ (409), 0 = υποδειξη''',
    'SELECT ''η στήλη ready_enforced υπάρχει ήδη'' AS msg'
  )
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE()
    AND TABLE_NAME   = '4a_task_types'
    AND COLUMN_NAME  = 'ready_enforced'
);
PREPARE st FROM @sql; EXECUTE st; DEALLOCATE PREPARE st;

-- ── 2. ΜΟΝΟ η open_code ───────────────────────────────────────────────
-- Είναι η ρίζα κάθε αλυσίδας: χωρίς κωδικό συνεργασίας, καμία από τις
-- επόμενες έξι δεν έχει νόημα. Οι υπόλοιπες μένουν 0.
UPDATE `4a_task_types`
   SET `ready_enforced` = 1
 WHERE `code` = 'open_code';

-- ── 3. Φράγμα λογικής ─────────────────────────────────────────────────
-- ready_enforced = 1 ΧΩΡΙΣ ready_check σημαίνει «φράξε με βάση το
-- τίποτα»: θα μπλόκαρε για πάντα, χωρίς κανέναν τρόπο να ικανοποιηθεί.
-- Ο έλεγχος πρέπει να γυρίσει 0.
SELECT COUNT(*) AS enforced_xwris_kanona
  FROM `4a_task_types`
 WHERE `ready_enforced` = 1 AND (`ready_check` IS NULL OR `ready_check` = '');

-- ── 4. Επαλήθευση ─────────────────────────────────────────────────────
SELECT `code`,
       IFNULL(`ready_check`, '—') AS chk,
       `ready_enforced` AS enforced,
       IFNULL(`ready_hint`, '—')  AS hint
  FROM `4a_task_types`
 ORDER BY `sort_order`;
